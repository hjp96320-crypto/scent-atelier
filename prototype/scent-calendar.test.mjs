import assert from 'node:assert/strict';
import {dateKey,moveDate,moveMonth,calendarMonth} from './scent-calendar.mjs';
assert.equal(dateKey(new Date(2026,0,1,0,5)),'2026-01-01','uses local date, not UTC');
assert.equal(moveDate('2024-02-28',1),'2024-02-29');
assert.equal(moveDate('2025-02-28',1),'2025-03-01');
assert.equal(moveMonth('2026-01',-1),'2025-12');
assert.equal(moveMonth('2026-12',1),'2027-01');
const entries=[{date:'2026-11-02',perfumeId:'one'},{date:'2026-11-02',perfumeId:'two'},{date:'2026-11-08',perfumeId:'one'},{date:'2026-10-31',perfumeId:'three'}];
const month=calendarMonth('2026-11',entries,'2026-11-08');
assert.equal(month.days.length,42);
assert.equal(month.days[0].key,'2026-10-26','week starts on Monday');
assert.equal(month.days.filter(d=>d.inMonth).length,30);
assert.equal(month.days.find(d=>d.key==='2026-11-02').count,2);
assert.equal(month.recordDays,2);
assert.equal(month.perfumeCount,2);
assert.equal(month.entries,3);
assert.equal(month.days.filter(d=>d.today).length,1);
assert.equal(month.days.find(d=>d.key==='2026-11-09').future,true);
assert.equal(calendarMonth('2024-02').days.filter(d=>d.inMonth).length,29);
console.log('PASS: local dates, month/year boundaries, leap days, diary counts and future states');
