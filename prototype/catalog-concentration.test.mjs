import assert from 'node:assert/strict';
import {perfumes} from './data.js';
import {filterCatalog} from './catalog-model.mjs';
import {namedConcentration,concentrationGroup} from './catalog-concentration.mjs';
assert.equal(namedConcentration('Example Eau De Parfum Intense'),'Eau de Parfum Intense');
assert.equal(namedConcentration('Example Extrait de Parfum'),'Extrait de Parfum');
assert.equal(namedConcentration('CK Cologne'),'');
assert.equal(namedConcentration('Le Parfum'),'');
assert.equal(namedConcentration('Elixir'),'');
assert.equal(concentrationGroup('浓度未单独标注'),'unknown');
const unknown=filterCatalog(perfumes,{concentration:'unknown'});
assert.ok(unknown.length>0);
assert.ok(unknown.every(p=>p.concentrationZh==='香水'&&!namedConcentration(p.name)));
const edt=filterCatalog(perfumes,{brand:'DIOR',query:'Sauvage',concentration:'edt'});
const edp=filterCatalog(perfumes,{brand:'DIOR',query:'Sauvage',concentration:'edp'});
assert.ok(edt.some(p=>p.id==='dior-sauvage-edt'));
assert.ok(edp.some(p=>p.id==='dior-sauvage-eau-de-parfum'));
assert.ok(!edt.some(p=>edp.some(q=>q.id===p.id)),'versions remain separate records');
assert.equal(new Set(perfumes.map(p=>p.id)).size,26335,'no speculative duplicate versions');
for(const p of perfumes)assert.ok(['edt','edp','parfum','cologne','other','unknown'].includes(p.concentrationKey));
console.log(`PASS: concentration parsing, unknown category, combined version filters and ${perfumes.length} preserved identities`);
