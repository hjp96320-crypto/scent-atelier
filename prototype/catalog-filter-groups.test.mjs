import assert from 'node:assert/strict';
import {perfumes,brandNames} from './data.js';
import {brandInitial,groupBrands,popularBrands,regionGroups} from './catalog-filter-groups.mjs';

const regions=[...new Set(perfumes.map(p=>p.region))];
const regional=regionGroups(regions),groupedRegions=regional.flatMap(g=>g.values);
assert.equal(regions.length,48);
assert.deepEqual(new Set(groupedRegions),new Set(regions));
assert.equal(groupedRegions.length,regions.length,'every country/region occurs once');
assert.deepEqual(regional.map(g=>g.label),['亚洲','欧洲','北美洲','南美洲','非洲','大洋洲','跨洲（欧亚）']);
assert.ok(regional.find(g=>g.label==='亚洲').values.includes('中国香港'));
assert.ok(regional.find(g=>g.label==='北美洲').values.includes('墨西哥'));
assert.deepEqual(new Set(regional.find(g=>g.label==='跨洲（欧亚）').values),new Set(['俄罗斯','土耳其']));
assert.deepEqual(regionGroups(['未知地区','法国','法国']).find(g=>g.label==='其他').values,['未知地区']);
assert.deepEqual(regionGroups([]),[]);
for(const group of regional)assert.deepEqual(group.values,[...group.values].sort((a,b)=>a.localeCompare(b,'zh')));

for(const [name,expected] of [['CHANEL','C'],['ÉSIKA','E'],['ÁLVAREZ GÓMEZ','A'],['ÅND','A'],['#QUEENSUNITED','Q'],['4711','0–9'],['  100 BON','0–9'],['...D.S. & DURGA','D'],['纯中文品牌','#'],['','#']])assert.equal(brandInitial(name),expected,name);
const brands=[...new Set(perfumes.map(p=>p.brand))],grouped=groupBrands(brands,brandNames);
assert.equal(brands.length,1263);
const popular=popularBrands(brands);
assert.equal(popular.length,12,'all curated shortcuts exist in the current catalog');
assert.deepEqual(popular.slice(0,4),['CHANEL','DIOR','HERMÈS','JO MALONE LONDON'],'requested brands lead the shortcut group');
assert.equal(new Set(popular).size,popular.length,'popular shortcuts never duplicate a brand');
assert.ok(popular.every(brand=>brands.includes(brand)&&brandNames[brand]),'shortcuts preserve real brand IDs and Chinese display names');
assert.deepEqual(popularBrands(['NOT A BRAND','DIOR','CHANEL','DIOR']),['CHANEL','DIOR'],'curated order ignores input order and unknown brands');
assert.deepEqual(popularBrands([]),[]);
assert.deepEqual(new Set(grouped.flatMap(g=>g.values)),new Set(brands));
assert.equal(grouped.flatMap(g=>g.values).length,brands.length,'original brand IDs are never merged by display aliases');
for(const group of grouped)assert.ok(group.values.every(brand=>brandInitial(brand)===group.label));
assert.deepEqual(groupBrands(['DIOR','CHANEL'],{DIOR:'阿迪奥',CHANEL:'香奈儿'}).flatMap(g=>g.values),['CHANEL','DIOR'],'ordering follows original brand names, not Chinese pinyin');
assert.deepEqual(groupBrands(['4711','100 BON','24']).flatMap(g=>g.values),['24','100 BON','4711']);
assert.ok(groupBrands(brands,brandNames,'香奈儿').flatMap(g=>g.values).includes('CHANEL'));
assert.ok(groupBrands(brands,brandNames,'chanel').flatMap(g=>g.values).includes('CHANEL'));
assert.ok(groupBrands(brands,brandNames,'alvarez gomez').flatMap(g=>g.values).includes('ÁLVAREZ GÓMEZ'));
assert.ok(groupBrands(brands,brandNames,'esika').flatMap(g=>g.values).includes('ÉSIKA'));
for(const [query,brand] of [['L’Artisan',"L'ARTISAN PARFUMEUR"],['D’Orsay',"D'ORSAY"],['D‘Orsay',"D'ORSAY"]])assert.ok(groupBrands(brands,brandNames,query).flatMap(g=>g.values).includes(brand),'smart apostrophes: '+query);
assert.deepEqual(groupBrands(['D’ORSAY'],{},"D'Orsay")[0].values,['D’ORSAY'],'source and query apostrophes both normalize');
assert.deepEqual(groupBrands(brands,brandNames,'not a real perfume house'),[]);
assert.deepEqual(groupBrands(brands,brandNames,'迪奥','C'),[],'query and letter selection combine');
assert.ok(groupBrands(brands,brandNames,'','D').every(g=>g.label==='D'));
assert.deepEqual(groupBrands(['BRAND A','BRAND B'],{'BRAND A':'同名','BRAND B':'同名'},'同名')[0].values,['BRAND A','BRAND B'],'equal translations retain separate original brands');
console.log(`PASS: ${regions.length} regions in ${regional.length} groups; ${brands.length} brands covered once; ${popular.length} popular shortcuts; original-name sorting and bilingual search`);
