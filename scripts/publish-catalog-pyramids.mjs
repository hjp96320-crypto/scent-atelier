// Publish the reviewed bulk artifact only after validating every target and stage.
import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {fileURLToPath,pathToFileURL} from 'node:url';
import rows from '../prototype/catalog-full-rows.js';

const root=fileURLToPath(new URL('../',import.meta.url));
const research=path.join(root,'research/catalog-pyramids-discovery/bulk-dry-run');
const input=path.join(research,'approved-pyramids.json');
const evidencePath=path.join(research,'approved-evidence.json');
const baselinePath=path.join(root,'research/catalog-pyramids.json');
const target=path.join(root,'prototype/catalog-pyramids.js');
const readJson=file=>JSON.parse(fs.readFileSync(file,'utf8'));
const approved=readJson(input),evidence=readJson(evidencePath),baseline=readJson(baselinePath);
const plainObject=value=>value!==null&&typeof value==='object'&&!Array.isArray(value);
const normalize=value=>String(value).normalize('NFKD').replace(/[\u0300-\u036f]/g,'').toLowerCase().replace(/[^a-z0-9]+/g,' ').trim();
const digest=value=>createHash('sha256').update(value).digest('hex');
assert.ok(plainObject(approved),'approved pyramids must be an object');
assert.ok(Array.isArray(evidence),'approved evidence must be an array');
assert.equal(Object.keys(baseline).length,313,'the original 313-row baseline must remain available');
const byRow=new Map();
for(const entry of evidence){
 assert.ok(plainObject(entry)&&Number.isSafeInteger(entry.sourceRowIndex),'evidence needs an integer sourceRowIndex');
 assert.ok(!byRow.has(entry.sourceRowIndex),`duplicate evidence for row ${entry.sourceRowIndex}`);
 byRow.set(entry.sourceRowIndex,entry);
}
assert.equal(Object.keys(approved).length,byRow.size,'pyramid and evidence counts must agree');
const sourceCounts={};
for(const [key,pyramid] of Object.entries(approved)){
 assert.match(key,/^(0|[1-9]\d*)$/,'row key must be a canonical nonnegative integer');
 const index=Number(key),row=rows[index],entry=byRow.get(index);
 assert.ok(Number.isSafeInteger(index)&&index<rows.length&&Array.isArray(row),`unknown catalog row ${key}`);
 assert.ok(entry,`missing evidence for row ${key}`);
 assert.ok(plainObject(pyramid),`invalid pyramid for row ${key}`);
 assert.deepEqual(Object.keys(pyramid).sort(),['base','heart','sourceLabel','sourceUrl','top'],`unexpected schema at row ${key}`);
 assert.equal(normalize(entry.target.brand),normalize(row[0]),`brand differs at row ${key}`);
 assert.equal(normalize(entry.target.name_perfume),normalize(row[1]),`title differs at row ${key}`);
 for(const stage of ['top','heart','base']){
  assert.ok(Array.isArray(pyramid[stage])&&pyramid[stage].length>0,`missing ${stage} at row ${key}`);
  assert.ok(pyramid[stage].every(note=>typeof note==='string'&&note.length>0&&note===note.trim()),`invalid ${stage} label at row ${key}`);
 }
 assert.ok(typeof pyramid.sourceLabel==='string'&&pyramid.sourceLabel.trim(),`missing source label at row ${key}`);
 assert.ok(typeof pyramid.sourceUrl==='string',`missing source URL at row ${key}`);
 const url=new URL(pyramid.sourceUrl);
 assert.ok(url.protocol==='https:'&&url.hostname&&!url.username&&!url.password,`invalid HTTPS URL at row ${key}`);
 const expectedHost={parfumo:'www.parfumo.com',fragrantica:'www.fragrantica.com'}[entry.selectedSource];
 assert.ok(expectedHost&&url.hostname===expectedHost,`source identity differs at row ${key}`);
 assert.equal(entry.candidateSource.URL,pyramid.sourceUrl,`evidence URL differs at row ${key}`);
 for(const [stage,column] of Object.entries({top:'Top_Notes',heart:'Middle_Notes',base:'Base_Notes'})){
  assert.deepEqual(pyramid[stage],entry.candidateSource[column].split(',').map(note=>note.trim()).filter(Boolean),`source notes were changed at row ${key}/${stage}`);
 }
 sourceCounts[entry.selectedSource]=(sourceCounts[entry.selectedSource]||0)+1;
}
for(const [key,pyramid] of Object.entries(baseline)){
 assert.deepEqual(approved[key],pyramid,`original baseline row ${key} was removed or changed`);
}
const header='// Generated by scripts/publish-catalog-pyramids.mjs; matching evidence in research/catalog-pyramids-discovery/bulk-dry-run/.\n';
const moduleText=header+'export const catalogPyramids = '+JSON.stringify(approved)+';\n';
const temporary=target+'.tmp';
fs.writeFileSync(temporary,moduleText,'utf8');
fs.renameSync(temporary,target);
const published=await import(pathToFileURL(target).href+'?sha='+digest(moduleText));
assert.deepEqual(published.catalogPyramids,approved,'published module did not round-trip');
const manifest={publishedAt:new Date().toISOString(),status:'published-to-local-prototype',count:Object.keys(approved).length,retainedBaseline:313,newPyramids:Object.keys(approved).length-313,sourceCounts,inputSha256:digest(fs.readFileSync(input)),evidenceSha256:digest(fs.readFileSync(evidencePath)),baselineSha256:digest(fs.readFileSync(baselinePath)),moduleSha256:digest(moduleText),target:'prototype/catalog-pyramids.js'};
fs.writeFileSync(path.join(research,'published-manifest.json'),JSON.stringify(manifest,null,2)+'\n','utf8');
console.log(JSON.stringify(manifest,null,2));
