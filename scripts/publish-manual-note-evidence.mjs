import assert from 'node:assert/strict';
import {readFileSync,writeFileSync} from 'node:fs';
import {perfumes} from '../prototype/data.js';

const records=JSON.parse(readFileSync(new URL('../research/catalog-pyramids-discovery/manual-research.json',import.meta.url),'utf8')).records;
const normalized=value=>value.normalize('NFD').replace(/[\u0300-\u036f]/g,'').toLowerCase().trim();
const stem=(name,concentration)=>{
 const value=normalized(name),suffix=' '+normalized(concentration);
 return value.endsWith(suffix)?value.slice(0,-suffix.length):value;
};
const output={};
for(const record of records.filter(r=>r.approvedForCatalog)){
 const target=perfumes.find(p=>p.id===record.id);
 assert.ok(target,record.id);
 assert.equal(normalized(target.brand),normalized(record.brand),record.id);
 assert.equal(stem(target.name,record.concentration),stem(record.name,record.concentration),record.id);
 if(target.concentration!=='浓度未单独标注')assert.equal(target.concentration,record.concentration,record.id);
 assert.ok(['top','heart','base'].every(s=>record.pyramid[s]?.length),record.id);
 assert.ok(record.sourceUrl?.startsWith('https://'),record.id);
 output[record.id]={
  concentration:record.concentration,
  pyramid:{...record.pyramid,sourceUrl:record.sourceUrl,sourceLabel:record.sourceType.startsWith('official')||record.sourceType==='brand-press-release'?'品牌公开香调资料':'商品与香水档案资料'},
 };
}
const unresolved=records.filter(r=>r.status==='unresolved'&&!r.approvedForCatalog).map(r=>r.id);
for(const id of unresolved)assert.ok(perfumes.some(p=>p.id===id),id);
writeFileSync(new URL('../prototype/catalog-note-overrides.mjs',import.meta.url),'// Generated by scripts/publish-manual-note-evidence.mjs; research/catalog-pyramids-discovery/manual-research.json retains version evidence.\nexport const catalogNoteOverrides = '+JSON.stringify(output,null,2)+';\nexport const unresolvedPyramidIds = '+JSON.stringify(unresolved)+';\n');
console.log(`Published ${Object.keys(output).length} product-specific note records`);
