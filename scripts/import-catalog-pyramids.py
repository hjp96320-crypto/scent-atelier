"""Conservatively join the cached Parfumo snapshot to existing catalog row IDs.

Requires an explicit concentration and exact normalized brand, title and year.
No fuzzy matching, inferred concentrations, brand aliases or year corrections.
"""
import csv
import gzip
import hashlib
import io
import json
import re
import unicodedata
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CACHE = ROOT / "research/catalog-pyramids"
RAW = CACHE / "02_Parfumo_Perfumes.csv.gz"
STAGES = {"top": "Top_Notes", "heart": "Middle_Notes", "base": "Base_Notes"}
CONCENTRATIONS = [
    ("extrait de parfum", "extrait"), ("eau de parfum", "edp"),
    ("eau de toilette", "edt"), ("eau de cologne", "edc"),
    ("edp", "edp"), ("edt", "edt"),
]


def normalize(value):
    value = "".join(c for c in unicodedata.normalize("NFKD", value.lower())
                    if not unicodedata.combining(c))
    return re.sub(r"[^a-z0-9]+", " ", value).strip()


def concentration_from_name(value):
    value = normalize(value)
    for label, concentration in CONCENTRATIONS:
        pattern = r"\b" + label + r"\b"
        if re.search(pattern, value):
            return " ".join(re.sub(pattern, "", value).split()), concentration
    return value, None


def source_identity(row):
    name = normalize(row["Name"])
    year = row["Release_Year"].removesuffix(".0")
    brand = normalize(row["Brand"])
    concentration = normalize(row["Concentration"])
    # Scraper appends these exact fields to some names. Remove only that suffix.
    suffix = " ".join(x for x in [brand, year, concentration] if x)
    if concentration and name.endswith(" " + suffix):
        name = name[:-len(suffix)].strip()
    stem, parsed = concentration_from_name(name)
    explicit = next((c for label, c in CONCENTRATIONS if label == concentration), None)
    # Different concentration metadata and title is an ambiguous record.
    if explicit and parsed and explicit != parsed:
        return None
    return brand, stem, explicit or parsed, year


def main():
    source = list(csv.DictReader(io.StringIO(gzip.decompress(RAW.read_bytes()).decode("utf-8-sig"))))
    with (ROOT / "research/catalog-100/hf-perfumes.csv").open(encoding="utf-8-sig") as handle:
        catalog = list(csv.DictReader(handle, delimiter="|"))
    urls = Counter(row["URL"] for row in source)
    index = defaultdict(list)
    for row in source:
        key = source_identity(row)
        if key and key[2] and urls[row["URL"]] == 1:
            index[key].append(row)
    output, provenance, counts = {}, [], Counter()
    for i, item in enumerate(catalog):
        stem, concentration = concentration_from_name(item["name_perfume"])
        if not concentration:
            continue
        counts["explicitConcentrationRows"] += 1
        if not re.fullmatch(r"\d{4}", item["years"]):
            continue
        key = normalize(item["brand"]), stem, concentration, item["years"]
        matches = index[key]
        if len(matches) != 1:
            continue
        counts["exactUniqueMatches"] += 1
        row = matches[0]
        if not all(row[column].strip() for column in STAGES.values()):
            continue
        pyramid = {stage: [note.strip() for note in row[column].split(",") if note.strip()]
                   for stage, column in STAGES.items()}
        if not all(pyramid.values()):
            continue
        pyramid.update(sourceUrl=row["URL"], sourceLabel="Parfumo 香水资料")
        output[str(i)] = pyramid
        provenance.append({"sourceRowIndex": i, "catalogBrand": item["brand"],
                           "catalogName": item["name_perfume"], "year": item["years"],
                           "concentration": concentration, "sourceRecord": row})
    counts["completePyramids"] = len(output)
    counts["sourceRecords"] = len(source)
    counts["excludedDuplicatedSourceUrls"] = sum(1 for row in source if urls[row["URL"]] != 1)
    notes = sorted({note for entry in output.values() for stage in STAGES for note in entry[stage]})
    report = {"date": "2026-11-08", "source": "https://github.com/JennyIseev/fragrance-analysis",
              "sourceSha256": hashlib.sha256(RAW.read_bytes()).hexdigest(),
              "matching": "exact normalized brand/title, explicit concentration, exact year; unique source URL and match; all stages required",
              "counts": dict(counts), "uniqueNotes": len(notes)}
    for name, value in [("matches.json", provenance), ("staged-notes.json", notes), ("report.json", report)]:
        (CACHE / name).write_text(json.dumps(value, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    (ROOT / "research/catalog-pyramids.json").write_text(json.dumps(output, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    module = "// Generated by scripts/import-catalog-pyramids.py; source details in research/catalog-pyramids/.\n"
    module += "export const catalogPyramids = " + json.dumps(output, ensure_ascii=False, separators=(",", ":")) + ";\n"
    (ROOT / "prototype/catalog-pyramids.js").write_text(module, encoding="utf-8")
    print(json.dumps(report, ensure_ascii=False))


if __name__ == "__main__":
    main()
